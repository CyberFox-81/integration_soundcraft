# Build SoundCraft for the browser, with the embedding bridge from patches/, into web/.
#
# Usage: scripts/build-soundcraft-web.sh [SOUNDCRAFT_CHECKOUT]
#
#   SOUNDCRAFT_CHECKOUT  an existing clone of github.com/storytold/soundcraft. Without it the
#                       script clones SOUNDCRAFT_REF into build/soundcraft.
#
# Needs: Rust with the wasm32-unknown-unknown target (rustup target add wasm32-unknown-unknown)
# and wasm-bindgen-cli at the version in SoundCraft's Cargo.lock
# (cargo install wasm-bindgen-cli --version <x.y.z> --locked). wasm-opt (binaryen) is used
# when installed and shrinks the download.
#
# Environment:
#   SOUNDCRAFT_REF  commit or tag to clone (default: the commit the patch was made against)
#   BUILD_STD=1    build the standard library from source (when the wasm32 target can't be
#                  installed through rustup but rust-src is available)
#   FAST=1         skip LTO and use parallel codegen: quicker builds, bigger wasm
#   CRAFT_FONTS_DIR  a clone of storytold/craft-fonts, to embed the shared Japanese fonts
set -euo pipefail

APP_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
SOUNDCRAFT_REF="${SOUNDCRAFT_REF:-6cf896e76c0ec82a11bf2494f209cfe7c8507f74}"
SRC="${1:-$APP_DIR/build/soundcraft}"
PATCH="$APP_DIR/patches/soundcraft-nextcloud.patch"
OUT="$APP_DIR/web"
TARGET_DIR="${CARGO_TARGET_DIR:-$SRC/target}"

if [ ! -e "$SRC/.git" ]; then
	git clone https://github.com/storytold/soundcraft.git "$SRC"
	git -C "$SRC" checkout --quiet "$SOUNDCRAFT_REF"
fi

if grep -rq 'soundcraft:ready' "$SRC/apps/soundcraft-web/src"; then
	echo "SoundCraft has the embedding bridge"
elif [ -s "$PATCH" ]; then
	git -C "$SRC" apply "$PATCH"
else
	echo "error: this SoundCraft has no embedding bridge, and there is no patch to add it" >&2
	exit 1
fi

cargo_args=(build --profile release -p soundcraft-web --target wasm32-unknown-unknown)
if [ "${BUILD_STD:-0}" = "1" ]; then
	export RUSTC_BOOTSTRAP=1
	cargo_args+=(-Zbuild-std=std,panic_abort)
fi
if [ "${FAST:-0}" = "1" ]; then
	export CARGO_PROFILE_RELEASE_LTO=off CARGO_PROFILE_RELEASE_CODEGEN_UNITS=16
fi
(cd "$SRC" && CARGO_TARGET_DIR="$TARGET_DIR" cargo "${cargo_args[@]}")

WASM_IN="$TARGET_DIR/wasm32-unknown-unknown/release/soundcraft-web.wasm"
STAGE="$(mktemp -d)"
trap 'rm -rf "$STAGE"' EXIT
OUT_NAME=soundcraft-web
wasm-bindgen --target web --weak-refs --no-typescript --out-dir "$STAGE" --out-name "$OUT_NAME" "$WASM_IN"

if command -v wasm-opt >/dev/null; then
	wasm-opt -Oz --enable-bulk-memory --enable-nontrapping-float-to-int --enable-sign-ext \
		--enable-mutable-globals --enable-reference-types --enable-multivalue \
		"$STAGE/${OUT_NAME}_bg.wasm" -o "$STAGE/${OUT_NAME}_bg.opt.wasm"
	mv "$STAGE/${OUT_NAME}_bg.opt.wasm" "$STAGE/${OUT_NAME}_bg.wasm"
else
	echo "note: wasm-opt not found; the wasm is not size-optimized"
fi

mkdir -p "$OUT"
hash() { sha256sum "$1" | cut -c1-16; }
# Content-hashed names: Nextcloud lets browsers cache app assets for months.
DEST="$OUT"
JS_NAME="soundcraft-web-$(hash "$STAGE/$OUT_NAME.js").js"
WASM_NAME="soundcraft-web-$(hash "$STAGE/${OUT_NAME}_bg.wasm").wasm"
rm -f "$OUT"/soundcraft-web-*.js "$OUT"/soundcraft-web-*.wasm
cp "$STAGE/$OUT_NAME.js" "$DEST/$JS_NAME"
cp "$STAGE/${OUT_NAME}_bg.wasm" "$DEST/$WASM_NAME"
# JavaScript the Rust code brings along (`#[wasm_bindgen(module = …)]`), imported by the glue.
rm -rf "$DEST/snippets"
if [ -d "$STAGE/snippets" ]; then cp -R "$STAGE/snippets" "$DEST/snippets"; fi

# SoundCraft's licenses and the attributions for the fonts and assets compiled into it.
for f in LICENSE-MIT LICENSE-APACHE NOTICE ATTRIBUTION.md ASSETS.md; do
	if [ -f "$SRC/$f" ]; then cp "$SRC/$f" "$OUT/SOUNDCRAFT-$f"; fi
done

cat > "$DEST/boot.js" <<BOOT
/*
 * SPDX-FileCopyrightText: 2026 Britton Couchman <brittondcouchman@gmail.com>
 * SPDX-License-Identifier: AGPL-3.0-or-later
 *
 * Starts SoundCraft in the editor's iframe (templates/frame.php).
 * Generated by scripts/build-soundcraft-web.sh from SoundCraft $(git -C "$SRC" rev-parse --short HEAD).
 */

function reportFailure(error) {
	console.error('SoundCraft could not start', error)
	if (window.parent !== window) {
		window.parent.postMessage({ type: 'soundcraft:failed', error: String(error?.message ?? error) }, window.location.origin)
	}
}

try {
	// Browsers start audio only after a user gesture: SoundCraft's audio output is built at
	// startup, so resume every AudioContext it creates on the first click or key press.
	const AudioContextBase = window.AudioContext || window.webkitAudioContext
	if (AudioContextBase) {
		const contexts = []
		const Resumable = function (options) {
			const context = new AudioContextBase(options)
			contexts.push(context)
			return context
		}
		Resumable.prototype = AudioContextBase.prototype
		window.AudioContext = Resumable
		if (window.webkitAudioContext) {
			window.webkitAudioContext = Resumable
		}
		const resume = () => contexts.forEach((context) => { if (context.state === 'suspended') { context.resume().catch(() => {}) } })
		for (const type of ['pointerdown', 'mousedown', 'touchstart', 'keydown']) {
			window.addEventListener(type, resume, { capture: true })
		}
	}
	const app = await import('./$JS_NAME')
	await app.default({ module_or_path: new URL('./$WASM_NAME', import.meta.url) })

} catch (error) {
	reportFailure(error)
}
BOOT

echo "SoundCraft web build:"
ls -lh "$OUT"
